using System.Collections.Immutable;
using System.Globalization;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Relevox.SourceGenerator.Tests;

/// <summary>
/// RVX0001 when the request's only handler is in generated code, which Relevox leaves out and MediatR's scan does
/// not. The handler still does not count; the message says where it is and how to count it.
/// </summary>
public sealed class GeneratedHandlerTests
{
    private const string Usings = "using Relevox; using System.Threading; using System.Threading.Tasks;\n";

    private const string Request = Usings + "namespace Shop; public sealed record Ping : IRequest<int>;";

    private const string Handler = """
        namespace Shop;
        public sealed class PingHandler : IRequestHandler<Ping, int>
        {
            public Task<int> Handle(Ping request, CancellationToken cancellationToken) => Task.FromResult(1);
        }
        """;

    [Fact]
    public void A_handler_in_a_file_named_as_generated_is_named_in_the_message()
    {
        string message = NoHandler(("Ping.cs", Request), ("Handlers.g.cs", Usings + Handler));

        message.ShouldBe("'Shop.Ping' has no handler the generator can use, so sending it would throw. 'Shop.PingHandler' in Handlers.g.cs implements one but is generated code, which Relevox leaves out; to count it, set generated_code = false for that file in .editorconfig.");
    }

    [Fact]
    public void A_handler_in_a_file_with_an_auto_generated_header_is_named_in_the_message()
    {
        string message = NoHandler(("Ping.cs", Request), ("Handlers.cs", "// <auto-generated/>\n" + Usings + Handler));

        message.ShouldContain("'Shop.PingHandler' in Handlers.cs implements one but is generated code");
        message.ShouldContain("set generated_code = false for that file in .editorconfig");
    }

    [Fact]
    public void A_handler_marked_GeneratedCode_is_named_in_the_message()
    {
        // .editorconfig does not undo the attribute, so the message points at the attribute instead.
        string marked = Handler.Replace("public sealed class", "[System.CodeDom.Compiler.GeneratedCode(\"tool\", \"1.0\")]\npublic sealed class", StringComparison.Ordinal);
        string message = NoHandler(("Ping.cs", Request), ("Handlers.cs", Usings + marked));

        message.ShouldContain("'Shop.PingHandler' in Handlers.cs implements one but is generated code");
        message.ShouldContain("to count it, remove the [GeneratedCode] attribute.");
        message.ShouldNotContain("generated_code");
    }

    [Fact]
    public void A_request_with_no_handler_anywhere_keeps_the_message_it_had()
    {
        string message = NoHandler(("Ping.cs", Request));

        message.ShouldBe("'Shop.Ping' has no handler in this project or the projects it references, so sending it would throw");
    }

    /// <summary>The one RVX0001 the analyzer reports over the files, as its message.</summary>
    private static string NoHandler(params (string Path, string Source)[] files)
    {
        CSharpCompilation compilation = CSharpCompilation.Create(
            "Shop",
            files.Select(static file => CSharpSyntaxTree.ParseText(file.Source, new CSharpParseOptions(LanguageVersion.Preview), file.Path)),
            GeneratorHarness.References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        ImmutableArray<Diagnostic> diagnostics = compilation.WithAnalyzers([new RelevoxAnalyzer()]).GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();

        Diagnostic diagnostic = diagnostics.ShouldHaveSingleItem();
        diagnostic.Id.ShouldBe("RVX0001");
        diagnostic.Severity.ShouldBe(DiagnosticSeverity.Warning);
        return diagnostic.GetMessage(CultureInfo.InvariantCulture);
    }
}
