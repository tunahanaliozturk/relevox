using System.Collections.Immutable;
using System.Globalization;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Relevox.SourceGenerator.Tests;

/// <summary>
/// RVX0001 when the request's only handler is in generated code, which Relevox leaves out and MediatR's scan does
/// not. The handler still does not count; the message says where it is and every reason it is left out.
/// </summary>
public sealed class GeneratedHandlerTests
{
    private const string Usings = "using Relevox; using System.Threading; using System.Threading.Tasks;\n";

    private const string Request = Usings + "namespace Shop; public sealed record Ping : IRequest<int>;";

    private const string Handler = """
        namespace Shop;
        public sealed class PingHandler : IRequestHandler<Ping, int>
        {
            public Task<int> Handle(Ping request, CancellationToken cancellationToken) => Task.FromResult(1);
        }
        """;

    private const string Marked = "[System.CodeDom.Compiler.GeneratedCode(\"tool\", \"1.0\")]\n";

    [Fact]
    public void A_handler_in_a_file_named_as_generated_is_named_in_the_message()
    {
        Diagnostic diagnostic = NoHandler(("Ping.cs", Request), ("Handlers.g.cs", Usings + Handler));

        diagnostic.GetMessage(CultureInfo.InvariantCulture).ShouldBe("'Shop.Ping' has no handler the generator can use, so sending it would throw. 'Shop.PingHandler' in Handlers.g.cs implements one but is generated code, which Relevox leaves out; to count it, set generated_code = false for that file in .editorconfig.");

        // The handler writer reads this and offers nothing: a second handler would be a duplicate.
        diagnostic.Properties.ShouldContainKey("HandlerOnlyInGeneratedCode");
    }

    [Fact]
    public void A_handler_in_a_file_with_an_auto_generated_header_is_named_in_the_message()
    {
        string message = Message(("Ping.cs", Request), ("Handlers.cs", "// <auto-generated/>\n" + Usings + Handler));

        message.ShouldContain("'Shop.PingHandler' in Handlers.cs implements one but is generated code");
        message.ShouldContain("to count it, set generated_code = false for that file in .editorconfig.");
    }

    [Fact]
    public void A_handler_marked_GeneratedCode_is_named_in_the_message()
    {
        // .editorconfig does not undo the attribute, so the message points at the attribute instead.
        string message = Message(("Ping.cs", Request), ("Handlers.cs", Usings + Handler.Replace("public sealed class", Marked + "public sealed class", StringComparison.Ordinal)));

        message.ShouldContain("'Shop.PingHandler' in Handlers.cs implements one but is generated code");
        message.ShouldContain("to count it, remove [GeneratedCode] from 'Shop.PingHandler'.");
        message.ShouldNotContain("generated_code");
    }

    [Fact]
    public void Every_reason_a_handler_is_left_out_is_named()
    {
        // The attribute on the type that contains the handler, in a file named as generated: either alone keeps it out.
        string handler = Usings + """
            namespace Shop;
            [System.CodeDom.Compiler.GeneratedCode("tool", "1.0")]
            public static class Handlers
            {
                public sealed class PingHandler : IRequestHandler<Ping, int>
                {
                    public Task<int> Handle(Ping request, CancellationToken cancellationToken) => Task.FromResult(1);
                }
            }
            """;

        string message = Message(("Ping.cs", Request), ("Handlers.g.cs", handler));

        message.ShouldContain("'Shop.Handlers.PingHandler' in Handlers.g.cs implements one");
        message.ShouldContain("to count it, set generated_code = false for that file in .editorconfig and remove [GeneratedCode] from 'Shop.Handlers'.");
    }

    [Fact]
    public void A_stream_handler_in_generated_code_is_named_in_the_message()
    {
        string message = Message(
            ("Numbers.cs", Usings + "namespace Shop; public sealed record Numbers : IStreamRequest<int>;"),
            ("Numbers.g.cs", Usings + """
                namespace Shop;
                public sealed class NumbersHandler : IStreamRequestHandler<Numbers, int>
                {
                    public async System.Collections.Generic.IAsyncEnumerable<int> Handle(Numbers request, [System.Runtime.CompilerServices.EnumeratorCancellation] CancellationToken cancellationToken)
                    {
                        await Task.Yield();
                        yield return 1;
                    }
                }
                """));

        message.ShouldContain("'Shop.NumbersHandler' in Numbers.g.cs implements one but is generated code");
    }

    [Fact]
    public void A_request_with_no_handler_anywhere_keeps_the_message_it_had()
    {
        Diagnostic diagnostic = NoHandler(("Ping.cs", Request));

        diagnostic.GetMessage(CultureInfo.InvariantCulture).ShouldBe("'Shop.Ping' has no handler in this project or the projects it references, so sending it would throw");
        diagnostic.Properties.ShouldNotContainKey("HandlerOnlyInGeneratedCode");
    }

    [Fact]
    public async Task Setting_generated_code_to_false_for_the_file_makes_the_handler_count()
    {
        // What the message tells a person to do, done: the analyzer reports nothing and the generator dispatches to it.
        // The compiler hands the setting both to the compilation and to analyzers, so the test does too.
        (string Path, string Source)[] files = [("Ping.cs", Request), ("Handlers.g.cs", Usings + Handler)];
        CSharpCompilation compilation = Compile(files).WithOptions(Options.WithSyntaxTreeOptionsProvider(new NotGenerated()));

        (await compilation.WithAnalyzers([new RelevoxAnalyzer()], new AnalyzerOptions([], new NotGeneratedOptions())).GetAnalyzerDiagnosticsAsync()).ShouldBeEmpty();
        CSharpGeneratorDriver.Create([new RelevoxGenerator().AsSourceGenerator()], parseOptions: new CSharpParseOptions(LanguageVersion.Preview))
            .RunGenerators(compilation)
            .GetRunResult().GeneratedTrees.Any(static tree => tree.ToString().Contains("PingHandler", StringComparison.Ordinal))
            .ShouldBeTrue();
    }

    private static readonly CSharpCompilationOptions Options = new(OutputKind.DynamicallyLinkedLibrary);

    private static string Message(params (string Path, string Source)[] files) =>
        NoHandler(files).GetMessage(CultureInfo.InvariantCulture);

    /// <summary>The one RVX0001 the analyzer reports over the files.</summary>
    private static Diagnostic NoHandler(params (string Path, string Source)[] files)
    {
        Diagnostic diagnostic = Analyze(Compile(files)).ShouldHaveSingleItem();
        diagnostic.Id.ShouldBe("RVX0001");
        diagnostic.Severity.ShouldBe(DiagnosticSeverity.Warning);
        return diagnostic;
    }

    private static CSharpCompilation Compile((string Path, string Source)[] files) =>
        CSharpCompilation.Create(
            "Shop",
            files.Select(static file => CSharpSyntaxTree.ParseText(file.Source, new CSharpParseOptions(LanguageVersion.Preview), file.Path)),
            GeneratorHarness.References,
            Options);

    private static ImmutableArray<Diagnostic> Analyze(Compilation compilation) =>
        compilation.WithAnalyzers([new RelevoxAnalyzer()]).GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();

    /// <summary><c>generated_code = false</c> for every file, as .editorconfig hands it to analyzers.</summary>
    private sealed class NotGeneratedOptions : AnalyzerConfigOptionsProvider
    {
        private static readonly Values Setting = new();

        public override AnalyzerConfigOptions GlobalOptions => Setting;

        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => Setting;

        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => Setting;

        private sealed class Values : AnalyzerConfigOptions
        {
            public override bool TryGetValue(string key, [System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out string? value)
            {
                value = key == "generated_code" ? "false" : null;
                return value is not null;
            }
        }
    }

    /// <summary><c>generated_code = false</c> for every file, as .editorconfig hands it to the compiler.</summary>
    private sealed class NotGenerated : SyntaxTreeOptionsProvider
    {
        public override GeneratedKind IsGenerated(SyntaxTree tree, CancellationToken cancellationToken) => GeneratedKind.NotGenerated;

        public override bool TryGetDiagnosticValue(SyntaxTree tree, string diagnosticId, CancellationToken cancellationToken, out ReportDiagnostic severity)
        {
            severity = ReportDiagnostic.Default;
            return false;
        }

        public override bool TryGetGlobalDiagnosticValue(string diagnosticId, CancellationToken cancellationToken, out ReportDiagnostic severity)
        {
            severity = ReportDiagnostic.Default;
            return false;
        }
    }
}
