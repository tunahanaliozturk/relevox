using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Relevox.Migration;

/// <summary>
/// Points at MediatR code left after the package swap, so the migration code fix has one id to hang off.
/// </summary>
/// <remarks>
/// <para>
/// The compiler reports the same leftovers under several ids: CS0246 for a <c>using</c>, CS0103 for
/// <c>MediatR.Unit.Value</c> in an expression, CS0400 for <c>global::MediatR</c>, CS1061 for
/// <c>AddMediatR</c>. An IDE's "Fix all" covers only the id it was started on, so a fix hung off those would
/// take one run per id and another after each rebuild. RVX0007 is one id for all of it.
/// </para>
/// <para>
/// Nothing is reported while the MediatR package is still referenced: a project half way through a gradual
/// migration keeps its MediatR code until it is ready.
/// </para>
/// </remarks>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class MediatRUsageAnalyzer : DiagnosticAnalyzer
{
    /// <summary>Property naming what was found, read by the code fix.</summary>
    public const string KindProperty = "Kind";

    /// <summary>A name rooted at <c>MediatR</c>.</summary>
    public const string NameKind = "Name";

    /// <summary><c>MediatRServiceConfiguration</c>.</summary>
    public const string ConfigurationKind = "Configuration";

    /// <summary>An <c>AddMediatR</c> call.</summary>
    public const string RegistrationKind = "Registration";

    /// <summary>
    /// <c>RequestExceptionActionProcessorStrategy</c>, which MediatR declares in
    /// <c>Microsoft.Extensions.DependencyInjection</c> and Relevox in <c>Relevox</c>.
    /// </summary>
    /// <remarks>
    /// It cannot follow MediatR into that namespace: an application half way through a migration, with both
    /// packages referenced, would see the same full name twice.
    /// </remarks>
    public const string StrategyKind = "Strategy";

    /// <summary>
    /// A <c>cref</c> in a documentation comment naming MediatR code, reported once for the whole <c>cref</c> and
    /// only when its Relevox counterpart resolves.
    /// </summary>
    public const string CrefKind = "Cref";

    // MediatR namespaces whose types Relevox has under the same names below Relevox.
    private static readonly HashSet<string> Mapped = new(System.StringComparer.Ordinal) { "Pipeline", "NotificationPublishers", "Entities" };

    // MediatR namespaces with no Relevox counterpart. Names in them are left for the compiler to point at.
    private static readonly HashSet<string> Unmapped = new(System.StringComparer.Ordinal) { "Registration", "Wrappers", "Licensing", "Internal" };

    /// <summary>
    /// Info, not a warning: the compiler already reports this code as an error once the MediatR package is
    /// gone. This exists so that one "Fix all" can reach every kind of it, since the IDE scopes a fix-all to
    /// the diagnostic id it was started on and the compiler gives the same code several different ids.
    /// </summary>
    public static readonly DiagnosticDescriptor Rule = new(
        id: "RVX0007",
        title: "MediatR code to move to Relevox",
        messageFormat: "'{0}' is MediatR code; the fix 'Move from MediatR to Relevox' rewrites it",
        category: "Relevox",
        defaultSeverity: DiagnosticSeverity.Info,
        isEnabledByDefault: true,
        helpLinkUri: HelpLink.To("rvx0007"),
        description: "Reported only where MediatR is no longer referenced and the name does not resolve. The code fix rewrites the namespace, the configuration type and the AddMediatR call; 'Fix all in solution' does the whole migration.");

    /// <inheritdoc />
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } = [Rule];

    /// <inheritdoc />
    public override void Initialize(AnalysisContext context)
    {
        // Files with an <auto-generated> header too: scaffolding tools write it on code that is then checked in and
        // kept like any other. Files a tool writes, source generators' output among them, are skipped by each action
        // (GeneratedFiles). Roslyn's "Fix all" skips header files whatever the analyzer does; the migration guides
        // say how to include them.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(static start =>
        {
            if (start.Compilation.GetTypeByMetadataName("Relevox.IBaseRequest") is null
                || start.Compilation.GetTypeByMetadataName("MediatR.IMediator") is not null)
            {
                return;
            }

            start.RegisterSyntaxNodeAction(GeneratedFiles.HandKept(AnalyzeName), SyntaxKind.IdentifierName);
            start.RegisterSyntaxNodeAction(GeneratedFiles.HandKept(AnalyzeInvocation), SyntaxKind.InvocationExpression);
            HashSet<IAssemblySymbol> relevox = RelevoxAssemblies.Of(start.Compilation);
            start.RegisterSyntaxNodeAction(GeneratedFiles.HandKept(context => AnalyzeCref(context, relevox)), SyntaxKind.XmlCrefAttribute);
        });
    }

    /// <summary>
    /// The <c>cref</c> with every MediatR name the code fix moves written as Relevox's: <c>MediatR</c> at the root
    /// of a name as <c>Relevox</c>, and <c>MediatRServiceConfiguration</c> as <c>RelevoxOptions</c>. Shared with the
    /// code fix, which writes what this analyzer checked resolves.
    /// </summary>
    /// <param name="cref">A <c>cref</c> from a documentation comment.</param>
    /// <returns>The <c>cref</c>, the same instance when there is nothing to move.</returns>
    public static CrefSyntax Moved(CrefSyntax cref)
    {
        IEnumerable<IdentifierNameSyntax> names = cref.DescendantNodes().OfType<IdentifierNameSyntax>().Where(static name =>
            name.Identifier.ValueText == "MediatRServiceConfiguration" || (name.Identifier.ValueText == "MediatR" && IsMovable(name)));
        return cref.ReplaceNodes(names, static (name, _) =>
            SyntaxFactory.IdentifierName(name.Identifier.ValueText == "MediatR" ? "Relevox" : "RelevoxOptions").WithTriviaFrom(name));
    }

    private static void AnalyzeCref(SyntaxNodeAnalysisContext context, HashSet<IAssemblySymbol> relevox)
    {
        // A cref is moved as a whole: one with MediatR names in its parameters as well as its type would not resolve
        // with only some of them moved. One whose Relevox counterpart does not resolve either, MediatR.Mediator for
        // example, is left for the compiler to point at, as unmapped names in code are. So is one that resolves
        // to something outside Relevox, such as a type of your own called RelevoxOptions.
        CrefSyntax cref = ((XmlCrefAttributeSyntax)context.Node).Cref;
        CrefSyntax moved = Moved(cref);
        if (moved == cref
            || context.SemanticModel.GetSymbolInfo(cref, context.CancellationToken) is { Symbol: not null } or { CandidateSymbols.Length: > 0 }
            || context.SemanticModel.GetSpeculativeSymbolInfo(cref.SpanStart, moved, SpeculativeBindingOption.BindAsTypeOrNamespace).Symbol is not { } symbol
            || !RelevoxAssemblies.Hold(relevox, symbol))
        {
            return;
        }

        Report(context, cref, CrefKind, cref.ToString());
    }

    private static void AnalyzeName(SyntaxNodeAnalysisContext context)
    {
        IdentifierNameSyntax name = (IdentifierNameSyntax)context.Node;

        // Inside an options object the fix turns into a lambda, the names are moved with it, by the AddMediatR
        // fix: an edit of their own would overlap that one, and "Fix all" would drop one of the two.
        if (KindOf(name, context.SemanticModel, context.CancellationToken) is not { } kind
            || InOptionsObject(name, context.SemanticModel, context.CancellationToken))
        {
            return;
        }

        string text = name.Identifier.ValueText;
        string? second = kind == NameKind ? SecondPart(name) : null;
        Report(context, name, kind, second is null ? text : $"{text}.{second}");
    }

    /// <summary>
    /// What RVX0007 reports this name as, or null when it is not reported. Shared with the code fix, which moves
    /// the names inside an options object itself.
    /// </summary>
    /// <param name="name">An identifier in code.</param>
    /// <param name="model">The semantic model of its tree.</param>
    /// <param name="cancellationToken">Cancels the work.</param>
    /// <returns><see cref="NameKind"/>, <see cref="ConfigurationKind"/>, <see cref="StrategyKind"/> or null.</returns>
    public static string? KindOf(IdentifierNameSyntax name, SemanticModel model, CancellationToken cancellationToken)
    {
        string text = name.Identifier.ValueText;
        if (text is not ("MediatR" or "MediatRServiceConfiguration" or "RequestExceptionActionProcessorStrategy")
            || name.FirstAncestorOrSelf<CrefSyntax>() is not null
            || model.GetSymbolInfo(name, cancellationToken) is { Symbol: not null } or { CandidateSymbols.Length: > 0 })
        {
            return null;
        }

        return text switch
        {
            "MediatRServiceConfiguration" => ConfigurationKind,

            // Only the simple name: Company.RequestExceptionActionProcessorStrategy is somebody else's type.
            "RequestExceptionActionProcessorStrategy" => name.Parent switch
            {
                QualifiedNameSyntax parent when parent.Right == name => null,
                MemberAccessExpressionSyntax parent when parent.Name == name => null,
                _ => StrategyKind,
            },
            _ => IsMovable(name) ? NameKind : null,
        };
    }

    /// <summary>
    /// Whether <c>MediatR</c>, as this name, roots a name that Relevox has a counterpart for, so the code fix can
    /// move it. Shared with the code fix, which renames every such using in a block at once.
    /// </summary>
    /// <param name="name">An identifier reading <c>MediatR</c>.</param>
    /// <returns>True when renaming it to <c>Relevox</c> keeps the code meaning the same thing.</returns>
    public static bool IsMovable(IdentifierNameSyntax name)
    {
        // MediatR has to be the root of the name: Company.MediatR.Foo is somebody else's namespace.
        switch (name.Parent)
        {
            case QualifiedNameSyntax qualified when qualified.Right == name:
            case MemberAccessExpressionSyntax access when access.Name == name:
            case AliasQualifiedNameSyntax alias when alias.Name == name && alias.Alias.Identifier.ValueText != "global":
                return false;
            default:
                break;
        }

        string? second = SecondPart(name);
        if (second is not null && Unmapped.Contains(second))
        {
            return false;
        }

        // In a plain using directive the second part is a namespace, which must be one Relevox has. An alias or a
        // using static names a type, which Relevox has under the same name.
        return name.FirstAncestorOrSelf<UsingDirectiveSyntax>() is not { Alias: null, StaticKeyword.RawKind: 0 }
            || second is null
            || Mapped.Contains(second);
    }

    private static void AnalyzeInvocation(SyntaxNodeAnalysisContext context)
    {
        InvocationExpressionSyntax invocation = (InvocationExpressionSyntax)context.Node;
        if (Registered(invocation) is { } method
            && context.SemanticModel.GetSymbolInfo(invocation, context.CancellationToken).Symbol is null)
        {
            Report(context, method, RegistrationKind, "AddMediatR");
        }
    }

    // The method name of an AddMediatR call, or null for any other call.
    private static SimpleNameSyntax? Registered(InvocationExpressionSyntax invocation) =>
        invocation.Expression switch
        {
            MemberAccessExpressionSyntax { Name.Identifier.ValueText: "AddMediatR" } access => access.Name,
            IdentifierNameSyntax { Identifier.ValueText: "AddMediatR" } identifier => identifier,
            _ => null,
        };

    /// <summary>
    /// The code an options object passed to <c>AddMediatR</c> is built from, when the code fix can turn it into
    /// the lambda <c>AddRelevox</c> takes; empty for any other argument. Shared with the code fix.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Two shapes qualify. The object made in the call itself, <c>new MediatRServiceConfiguration { ... }</c> with
    /// or without a chain of calls after it, comes back as that expression. A local made the same way in the block
    /// that holds the call comes back as its declaration followed by the statements that fill it in: plain ones,
    /// <c>config.Member(...);</c> or <c>config.Member = value;</c>, with the local used nowhere else.
    /// </para>
    /// <para>
    /// Those statements then run when <c>AddRelevox</c> calls the lambda, after the statements between them and the
    /// call. A statement may stand in between only when neither side can affect the other (ADR 0029 states the
    /// rule); the moved code may declare no variable and contain no <c>await</c>; and no preprocessor directive may
    /// stand between the declaration and the call, where it could hide another use of the local.
    /// </para>
    /// </remarks>
    /// <param name="argument">An argument of an <c>AddMediatR</c> call.</param>
    /// <param name="model">The semantic model of its tree.</param>
    /// <param name="cancellationToken">Cancels the work.</param>
    /// <returns>The expression, or the declaration and the statements in order; empty when nothing can be moved.</returns>
    public static ImmutableArray<SyntaxNode> OptionsObject(ArgumentSyntax argument, SemanticModel model, CancellationToken cancellationToken)
    {
        if (argument.Parent?.Parent is not InvocationExpressionSyntax call || Registered(call) is null)
        {
            return [];
        }

        if (Creation(argument.Expression) is ObjectCreationExpressionSyntax && !Awaits(argument.Expression))
        {
            // The code fix calls the lambda's parameter options, which must not hide a variable the code uses.
            return model.LookupSymbols(argument.SpanStart, name: "options").IsEmpty ? [argument.Expression] : [];
        }

        if (argument.Expression is not IdentifierNameSyntax reference
            || model.GetSymbolInfo(reference, cancellationToken).Symbol is not ILocalSymbol local
            || call.FirstAncestorOrSelf<StatementSyntax>() is not { Parent: BlockSyntax block } statement
            || call.Ancestors().TakeWhile(node => node != statement).Any(static node => node is AnonymousFunctionExpressionSyntax)
            || local.DeclaringSyntaxReferences.Length != 1
            || local.DeclaringSyntaxReferences[0].GetSyntax(cancellationToken) is not VariableDeclaratorSyntax
            {
                Initializer.Value: { } value,
                Parent: VariableDeclarationSyntax { Variables.Count: 1, Parent: LocalDeclarationStatementSyntax { UsingKeyword.RawKind: 0, Modifiers.Count: 0 } declaration } variables,
            }
            || declaration.Parent != block
            || Creation(value) is not { } creation
            || (creation is ImplicitObjectCreationExpressionSyntax && !IsConfiguration(variables.Type)))
        {
            return [];
        }

        int first = block.Statements.IndexOf(declaration);
        int last = block.Statements.IndexOf(statement);
        List<SyntaxNode> parts = [declaration];
        List<StatementSyntax> passed = [];
        for (int index = first + 1; index < last; index++)
        {
            StatementSyntax between = block.Statements[index];
            switch (Uses(between, local, model, cancellationToken))
            {
                case 0:
                    passed.Add(between);
                    break;
                case 1 when Fills(between, local.Name):
                    parts.Add(between);
                    break;
                default:
                    return [];
            }
        }

        if (first > last
            || Uses(statement, local, model, cancellationToken) != 1
            || block.Statements.Skip(last + 1).Any(later => Uses(later, local, model, cancellationToken) > 0)
            || block.DescendantTrivia(TextSpan.FromBounds(declaration.SpanStart, statement.SpanStart)).Any(static trivia => trivia.IsDirective || trivia.IsKind(SyntaxKind.DisabledTextTrivia)))
        {
            return [];
        }

        // The moved code, which runs later, when AddRelevox calls the lambda: the declaration's value and the statements.
        SyntaxNode[] moving = [value, .. parts.Skip(1)];
        foreach (SyntaxNode part in moving)
        {
            DataFlowAnalysis? flow = part is ExpressionSyntax expression ? model.AnalyzeDataFlow(expression) : model.AnalyzeDataFlow((StatementSyntax)part);
            if (flow is not { Succeeded: true, VariablesDeclared.IsEmpty: true } || Awaits(part))
            {
                return [];
            }
        }

        // Statements in between stay where they are, so the moved code runs after them. That is allowed only when
        // neither side can affect the other: the moved code takes nothing but plain values, and the statements in
        // between mention no variable, field, property or event it mentions.
        if (passed.Count > 0)
        {
            HashSet<ISymbol> mentioned = new(moving.SelectMany(part => State(part, model, cancellationToken)), SymbolEqualityComparer.Default);
            if (!moving.All(part => Plain(part, model, cancellationToken))
                || passed.Any(between => State(between, model, cancellationToken).Any(mentioned.Contains)))
            {
                return [];
            }
        }

        return [.. parts];
    }

    // An await cannot move into the lambda, which is not async; one inside a lambda already in the code can.
    private static bool Awaits(SyntaxNode node) =>
        node.DescendantNodesAndSelf(static child => child is not AnonymousFunctionExpressionSyntax).OfType<AwaitExpressionSyntax>().Any();

    // The variables, fields, properties and events the code names: what a statement could change or read.
    private static IEnumerable<ISymbol> State(SyntaxNode node, SemanticModel model, CancellationToken cancellationToken) =>
        node.DescendantNodesAndSelf().OfType<SimpleNameSyntax>()
            .Select(name => model.GetSymbolInfo(name, cancellationToken).Symbol)
            .Where(static symbol => symbol is ILocalSymbol or IParameterSymbol or IPropertySymbol or IEventSymbol or IFieldSymbol { IsConst: false })
            .Select(static symbol => symbol!);

    /// <summary>
    /// Whether every argument and assigned value in the code, outside lambdas, is a plain value: a literal,
    /// <c>default</c>, a <c>typeof</c> or a member of one, a constant or enum member, a lambda, or a read of a
    /// local or parameter. Evaluating such code later than written cannot change what it evaluates to on its own.
    /// </summary>
    private static bool Plain(SyntaxNode node, SemanticModel model, CancellationToken cancellationToken) =>
        node.DescendantNodesAndSelf(static child => child is not AnonymousFunctionExpressionSyntax)
            .Select(static child => child switch
            {
                ArgumentSyntax argument => argument.Expression,
                AssignmentExpressionSyntax assignment => assignment.Right,
                _ => null,
            })
            .All(value => value is null || value switch
            {
                LiteralExpressionSyntax or DefaultExpressionSyntax or TypeOfExpressionSyntax or AnonymousFunctionExpressionSyntax => true,
                MemberAccessExpressionSyntax { Expression: TypeOfExpressionSyntax } => true,
                IdentifierNameSyntax or MemberAccessExpressionSyntax => model.GetSymbolInfo(value, cancellationToken).Symbol is ILocalSymbol or IParameterSymbol or IFieldSymbol { IsConst: true },
                _ => false,
            });

    /// <summary>The object creation at the start of <c>new MediatRServiceConfiguration { ... }.Call(...)</c>, or null.</summary>
    private static BaseObjectCreationExpressionSyntax? Creation(ExpressionSyntax expression)
    {
        while (expression is InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax { Expression: { } receiver } })
        {
            expression = receiver;
        }

        // MediatR's configuration takes no constructor arguments, and only plain assignments can move into a lambda.
        return expression is BaseObjectCreationExpressionSyntax creation
            && creation.ArgumentList is null or { Arguments.Count: 0 }
            && (creation is ImplicitObjectCreationExpressionSyntax || IsConfiguration(((ObjectCreationExpressionSyntax)creation).Type))
            && (creation.Initializer is null
                || (creation.Initializer.IsKind(SyntaxKind.ObjectInitializerExpression)
                    && creation.Initializer.Expressions.All(static member => member is AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.SimpleAssignmentExpression, Left: IdentifierNameSyntax })))
            ? creation
            : null;
    }

    private static bool IsConfiguration(TypeSyntax type) =>
        type switch
        {
            QualifiedNameSyntax qualified => qualified.Right,
            AliasQualifiedNameSyntax alias => alias.Name,
            SimpleNameSyntax simple => simple,
            _ => null,
        } is IdentifierNameSyntax { Identifier.ValueText: "MediatRServiceConfiguration" };

    // config.Member(...); or config.Member = value;
    private static bool Fills(StatementSyntax statement, string local)
    {
        ExpressionSyntax? node = statement switch
        {
            ExpressionStatementSyntax { Expression: InvocationExpressionSyntax invocation } => invocation,
            ExpressionStatementSyntax { Expression: AssignmentExpressionSyntax { RawKind: (int)SyntaxKind.SimpleAssignmentExpression, Left: MemberAccessExpressionSyntax member } } => member,
            _ => null,
        };

        while (node is InvocationExpressionSyntax or MemberAccessExpressionSyntax)
        {
            node = node is InvocationExpressionSyntax invocation ? invocation.Expression : ((MemberAccessExpressionSyntax)node).Expression;
        }

        return node is IdentifierNameSyntax root && root.Identifier.ValueText == local;
    }

    private static int Uses(SyntaxNode node, ILocalSymbol local, SemanticModel model, CancellationToken cancellationToken) =>
        node.DescendantNodesAndSelf().OfType<IdentifierNameSyntax>().Count(name =>
            name.Identifier.ValueText == local.Name && SymbolEqualityComparer.Default.Equals(model.GetSymbolInfo(name, cancellationToken).Symbol, local));

    /// <summary>Whether the node is part of an options object the code fix turns into a lambda.</summary>
    private static bool InOptionsObject(SyntaxNode node, SemanticModel model, CancellationToken cancellationToken)
    {
        foreach (SyntaxNode ancestor in node.Ancestors())
        {
            if (ancestor is ArgumentSyntax argument && !OptionsObject(argument, model, cancellationToken).IsEmpty)
            {
                return true;
            }

            // A local declared, or filled in, by this statement and passed to AddMediatR further down the block.
            if (ancestor is StatementSyntax { Parent: BlockSyntax block } statement
                && block.Statements.SkipWhile(candidate => candidate != statement).Skip(1)
                    .SelectMany(static candidate => candidate.DescendantNodes().OfType<ArgumentSyntax>())
                    .Any(candidate => candidate.Expression is IdentifierNameSyntax && OptionsObject(candidate, model, cancellationToken).Contains(statement)))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>The part after <c>MediatR</c> in <c>MediatR.Pipeline</c> or <c>MediatR.Unit.Value</c>.</summary>
    private static string? SecondPart(IdentifierNameSyntax name)
    {
        SyntaxNode node = name.Parent is AliasQualifiedNameSyntax alias ? alias : name;
        return node.Parent switch
        {
            QualifiedNameSyntax qualified when qualified.Left == node => qualified.Right.Identifier.ValueText,
            MemberAccessExpressionSyntax access when access.Expression == node => access.Name.Identifier.ValueText,
            _ => null,
        };
    }

    private static void Report(SyntaxNodeAnalysisContext context, SyntaxNode node, string kind, string shown) =>
        context.ReportDiagnostic(Diagnostic.Create(
            Rule,
            node.GetLocation(),
            ImmutableDictionary<string, string?>.Empty.Add(KindProperty, kind),
            shown));
}
