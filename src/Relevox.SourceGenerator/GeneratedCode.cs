using System;
using System.IO;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Relevox.SourceGenerator;

/// <summary>
/// What the compiler treats as generated code when an analyzer asks not to see it, so the generator can leave out
/// the same code the analyzer never sees.
/// </summary>
/// <remarks>
/// The rules are Roslyn's: the <c>generated_code</c> setting in .editorconfig wins; otherwise a file named
/// <c>*.g.cs</c>, <c>*.g.i.cs</c>, <c>*.designer.cs</c>, <c>*.generated.cs</c> or
/// <c>TemporaryGeneratedFile_*</c>, or one whose first comment says <c>&lt;auto-generated&gt;</c>; and for a
/// type, a <c>[GeneratedCode]</c> attribute on it or a type containing it. Output of other source generators
/// needs no rule here: this generator never sees it.
/// </remarks>
internal static class GeneratedCode
{
    private static readonly string[] Suffixes = [".designer", ".generated", ".g", ".g.i"];

    public static bool Contains(SyntaxTree tree, Compilation compilation, CancellationToken cancellationToken) =>
        compilation.Options.SyntaxTreeOptionsProvider?.IsGenerated(tree, cancellationToken) switch
        {
            GeneratedKind.MarkedGenerated => true,
            GeneratedKind.NotGenerated => false,
            _ => IsGeneratedFileName(tree.FilePath) || BeginsWithAutoGeneratedComment(tree, cancellationToken),
        };

    public static bool IsMarked(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
        {
            if (current.GetAttributes().Any(static attribute => attribute.AttributeClass?.ToDisplayString() == "System.CodeDom.Compiler.GeneratedCodeAttribute"))
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsGeneratedFileName(string path)
    {
        if (string.IsNullOrEmpty(path))
        {
            return false;
        }

        string name = Path.GetFileName(path);
        if (name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        string stem = Path.GetFileNameWithoutExtension(path);
        return Path.GetExtension(path).Length > 0
            && Suffixes.Any(suffix => stem.EndsWith(suffix, StringComparison.OrdinalIgnoreCase));
    }

    private static bool BeginsWithAutoGeneratedComment(SyntaxTree tree, CancellationToken cancellationToken) =>
        tree.GetRoot(cancellationToken).GetLeadingTrivia().Any(static trivia =>
            trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)
                ? trivia.ToString().IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0
                    || trivia.ToString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
                : false);
}
